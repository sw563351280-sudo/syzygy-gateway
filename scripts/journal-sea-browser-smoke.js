'use strict';
const fs = require('node:fs'), path = require('node:path'), express = require('express');
const assert = require('node:assert/strict'), puppeteer = require('puppeteer-core');
const { WebSocketServer } = require('ws');
const root = path.join(__dirname,'..');
const titles = ['十月五日，凌晨到正午','雪松、边界与遗迹之间','把晚风留在这里','晨光经过窗边','没有说出口的那一句','海面还很安静','一盏灯，等你回来','今天的云走得很慢','写到这里，先停一停'];
const fixture = Array.from({ length:26 },(_,i) => ({ id:'journal_fixture_' + i, title:titles[i % titles.length], created_at:new Date(Date.parse('2026-10-05T06:19:00Z') - i * 12 * 3600000).toISOString(), visibility:'sealed',content:null,request_status:null }));
fixture[19].title = '<img src=x onerror="window.injected=true">长标题'.repeat(8);
fixture[20].visibility = 'revealed'; fixture[20].content = '获准打开后才出现的正文。\n<script>window.injected=true</script>';
async function main() {
  const app = express(); app.use(express.json());
  let failPageTwo = false, failList = false, failRequest = false, requested = 0;
  const pages = [];
  app.get('/api/private-journal',(req,res) => {
    const page = Number(req.query.page || 1); pages.push(page);
    if (failList || (page === 2 && failPageTwo)) return res.status(503).json({ error:'暂时打不开' });
    res.json({ entries:fixture.slice((page-1)*20,page*20), total:fixture.length });
  });
  app.post('/api/private-journal/:id/request-reveal',(req,res) => {
    requested++;
    if (failRequest) return res.status(503).json({ error:'暂未送达' });
    const entry = fixture.find(e=>e.id === req.params.id); entry.request_status = 'requested';
    res.json({ success:true,entry });
  });
  app.get('/api/home/summary',(_req,res)=>res.json({ days:535,date:'2026-10-07',nextMilestone:600,todos:[],schedules:[],letter:null,calendarAvailable:true,musicAvailable:false }));
  app.get('/api/sync-config',(_req,res)=>res.json({ chatSessions:[],suppliers:[] }));
  app.get('/api/music/status',(_req,res)=>res.json({ configured:false,session:{ state:'closed',mode:'local' } }));
  app.use('/api',(_req,res)=>res.json({ success:true,config:{},data:[],status:{},favorites:[],todos:[],active:[],records:[] }));
  app.get('/diary-logs',(_req,res)=>res.json([]));
  app.use(express.static(path.join(root,'public')));
  const server = app.listen(0,'127.0.0.1'); await new Promise(r=>server.once('listening',r));
  const ws = new WebSocketServer({ server }); let browser;
  try {
    const executablePath = ['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(fs.existsSync);
    browser = await puppeteer.launch({ executablePath,headless:true,args:['--mute-audio'] });
    const page = await browser.newPage(), errors = [];
    page.on('pageerror',e=>errors.push(e.message));
    await page.setRequestInterception(true);
    page.on('request',r=>r.url().startsWith('http') && !r.url().startsWith('http://127.0.0.1:') ? r.abort() : r.continue());
    await page.evaluateOnNewDocument(()=>localStorage.setItem('syzygy_visual_theme','new'));
    await page.setViewport({ width:1280,height:1000 });
    await page.goto(`http://127.0.0.1:${server.address().port}/`,{ waitUntil:'networkidle0' });
    await page.evaluate(()=>goView('private-journal'));
    await page.waitForFunction(()=>document.querySelectorAll('.journal-sea-row').length===20);
    await page.evaluate(()=>document.fonts.ready);
    const layout = await page.evaluate(()=>{
      const main = document.querySelector('.journal-sea-main').getBoundingClientRect();
      const row = document.querySelector('.journal-sea-row').getBoundingClientRect();
      return { width:main.width,left:main.left,rowHeight:row.height,filter:getComputedStyle(document.body,'::before').filter,visible:[...document.querySelectorAll('.journal-sea-row')].filter(r=>r.getBoundingClientRect().bottom <= innerHeight).length };
    });
    assert.equal(layout.width,640); assert.ok(layout.left >= 102 && layout.left <= 128); assert.equal(layout.rowHeight,56);
    assert.ok(layout.visible>=8 && layout.visible<=12); assert.equal(layout.filter,'none');
    assert.equal(await page.$eval('#privateJournalSea',e=>e.textContent.includes('SHEN WANG')),false);
    assert.equal(await page.$eval('#privateJournalSea',e=>e.textContent.includes('只有沈望愿意')),false);
    assert.equal(await page.$eval('#starmap',e=>getComputedStyle(e).display),'none');
    await page.screenshot({ path:path.join(root,'qa-journal-sea-1280.png') });
    await page.focus('.journal-sea-row'); await page.keyboard.press('Enter');
    await page.waitForFunction(()=>document.querySelector('#journalSeaReader').open);
    assert.equal(requested,0,'opening a row does not submit a request');
    assert.equal(await page.$('#journalSeaReader .journal-sea-reader-body'),null,'sealed reader never renders content');
    assert.ok(await page.$('#journalSeaReader .journal-sea-fake-ink path'));
    await page.screenshot({ path:path.join(root,'qa-journal-sea-reader-1280.png') });
    await page.keyboard.press('Escape');
    assert.equal(await page.evaluate(()=>document.activeElement.dataset.entryId),'journal_fixture_0');
    failPageTwo = true; await page.click('#journalSeaMore');
    await page.waitForFunction(()=>document.querySelector('#journalSeaStatus button'));
    assert.equal(await page.$$eval('.journal-sea-row',r=>r.length),20,'failed pagination retains current list');
    failPageTwo = false; await page.click('#journalSeaStatus button');
    await page.waitForFunction(()=>document.querySelectorAll('.journal-sea-row').length===26);
    assert.deepEqual(pages.slice(-2),[2,2],'retry does not skip the failed page');
    await page.click('[data-entry-id="journal_fixture_20"]');
    assert.match(await page.$eval('.journal-sea-reader-body',e=>e.textContent),/获准打开/);
    assert.equal(await page.evaluate(()=>window.injected),undefined,'titles and body are rendered as text');
    await page.keyboard.press('Escape');
    await page.evaluate(()=>window.scrollTo(0,0));
    await page.click('[data-entry-id="journal_fixture_0"]');
    fixture[0].visibility = 'revealed'; fixture[0].content = '新的正文。';
    await page.evaluate(()=>privateJournalLoad(true));
    await page.waitForFunction(()=>document.querySelector('.journal-sea-reader-body')?.textContent==='新的正文。');
    assert.equal(await page.$('.journal-sea-fake-ink'),null,'open reader refreshes after a reveal');
    await page.keyboard.press('Escape');
    await page.click('[data-entry-id="journal_fixture_1"]');
    failRequest = true; await page.click('.journal-sea-reader-request');
    await page.waitForFunction(()=>document.querySelector('.journal-sea-reader-request')?.disabled===false);
    assert.equal(await page.$eval('#journalSeaReader',e=>e.open),true,'failed request keeps reader open');
    failRequest = false;
    await page.evaluate(()=>{ sendChat = async()=>{ window.fixtureSent = document.getElementById('chatInput').value; }; });
    await page.click('.journal-sea-reader-request');
    await page.waitForFunction(()=>document.body.dataset.view==='chat');
    assert.equal(await page.$eval('#journalSeaReader',e=>e.open),false);
    assert.match(await page.evaluate(()=>window.fixtureSent),/journal_fixture_1/);
    assert.equal(requested,2);
    await page.evaluate(()=>goView('private-journal')); await page.waitForFunction(()=>document.querySelectorAll('.journal-sea-row').length===20);
    await page.evaluate(()=>document.getElementById('toast').classList.remove('show'));
    for (const width of [1024,393,320]) {
      await page.setViewport({ width,height:width>700 ? 900 : 852 });
      await page.evaluate(()=>window.scrollTo(0,0));
      await page.screenshot({ path:path.join(root,`qa-journal-sea-${width}.png`) });
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no mobile horizontal overflow');
      await page.click('[data-entry-id="journal_fixture_1"]');
      await page.screenshot({ path:path.join(root,`qa-journal-sea-reader-${width}.png`) });
      assert.ok(await page.$eval('#journalSeaReader',d=>d.scrollWidth<=d.clientWidth),'reader fits screen');
      await page.evaluate(()=>applyVisualTheme('classic'));
      assert.equal(await page.$eval('#journalSeaReader',d=>d.open),false);
      assert.equal(await page.$eval('#privateJournalSea',e=>getComputedStyle(e).display),'none');
      assert.equal(await page.$eval('#privateJournalSea',e=>e.inert),true);
      assert.notEqual(await page.$eval('.private-journal-page',e=>getComputedStyle(e).display),'none');
      await page.evaluate(()=>applyVisualTheme('new'));
    }
    failList = true; await page.evaluate(()=>privateJournalLoad(true));
    await page.waitForFunction(()=>document.querySelector('#journalSeaList button'));
    failList = false; await page.click('#journalSeaList button');
    await page.waitForFunction(()=>document.querySelectorAll('.journal-sea-row').length===20);
    await page.click('#journalSeaBack');
    assert.equal(await page.evaluate(()=>document.body.dataset.seaPage),'false');
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({ ok:true,layout,widths:[1280,1024,393,320],checks:['directory','sealed marks','reveal update','request failure and chat handoff','pagination retry','XSS','keyboard focus','theme rollback'],pageErrors:errors }));
  } finally { await browser?.close(); ws.close(); await new Promise(r=>server.close(r)); }
}
main().catch(e=>{ console.error(e); process.exitCode=1; });
